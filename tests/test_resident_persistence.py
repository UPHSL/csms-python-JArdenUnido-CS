# ---------------------------------------------------------------------------
# TEST 7 – Persistence Works Across Repository Instances
# ---------------------------------------------------------------------------

def test_persistence_across_repository_instances(db_path: str) -> None:
    """Data saved through one repository instance is visible to a second one.

    This test demonstrates that the persistence layer uses real on-disk
    storage, not just an in-memory Python structure.  If the repository were
    backed by a plain list or dict, the second instance would see an empty
    store and find_by_id would return None.
    """
    # First repository instance – used to save the Resident.
    repo_one = ResidentRepository(db_path)
    resident = make_resident(first_name="Ana", last_name="Reyes")
    repo_one.save(resident)
    saved_id = resident.id

    # Second repository instance – created independently, same database file.
    repo_two = ResidentRepository(db_path)
    retrieved = repo_two.find_by_id(saved_id)  # type: ignore[arg-type]

    assert retrieved is not None
    assert retrieved.id == saved_id
    assert retrieved.first_name == "Ana"
    assert retrieved.last_name == "Reyes"


# ---------------------------------------------------------------------------
# TEST 8 – Student-Designed: Contact Number Is Stored as Text
# ---------------------------------------------------------------------------
#
# What this test verifies:
#   The contact_number field is stored in SQLite as TEXT, so the leading zero
#   in a Philippine mobile number (e.g. "09171234567") is never silently
#   dropped.  If the column were declared as INTEGER, SQLite would store the
#   value 9171234567 and the leading zero would be lost on retrieval.
#
# Why this scenario was selected:
#   The T03 requirements explicitly call out that "09171234567 must NOT become
#   9171234567".  A dedicated test for this makes the contract visible and
#   catches any future schema change that accidentally declares the column
#   as a numeric type.
#
# What failure it is designed to detect:
#   If the database schema is changed so that contact_number is stored as
#   INTEGER or NUMERIC, the retrieved value would be the integer 9171234567
#   (a string without the leading zero).  This test would then fail at the
#   exact assertion that compares the retrieved string to "09171234567".

def test_contact_number_leading_zero_is_preserved(repo: ResidentRepository) -> None:
    """The leading zero of a Philippine mobile number survives the DB round-trip."""
    resident = make_resident(contact_number="09171234567")
    repo.save(resident)

    retrieved = repo.find_by_id(resident.id)  # type: ignore[arg-type]

    assert retrieved is not None
    assert retrieved.contact_number == "09171234567"
    # Explicitly confirm it is a string, not a number missing its leading zero.
    assert isinstance(retrieved.contact_number, str)
    assert retrieved.contact_number.startswith("0")
