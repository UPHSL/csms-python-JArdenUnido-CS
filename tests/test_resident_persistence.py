"""Automated tests for Resident persistence (T03).

These tests verify that :class:`~csms.repositories.resident_repository.ResidentRepository`
correctly stores and retrieves :class:`~csms.models.resident.Resident` objects
using a real SQLite database.  Every test receives a freshly initialised
temporary database file through the ``db_path`` fixture so that tests are
fully isolated from each other and from the development database.

Test inventory
--------------
1. test_persist_a_resident                – Resident can be saved without error.
2. test_resident_receives_an_identifier   – Saved Resident gets a non-None id.
3. test_retrieve_resident_by_identifier   – Saved Resident is returned by its id.
4. test_resident_information_is_preserved – All fields survive the round-trip.
5. test_active_status_is_preserved        – Default "Active" status survives.
6. test_missing_resident_returns_none     – Unknown id safely returns None.
7. test_persistence_across_instances      – Two repo instances share the same DB.
8. test_contact_number_stored_as_text     – Leading zero is not dropped (student-designed).
"""

import os
import tempfile

import pytest

from csms.models.resident import Resident
from csms.repositories.resident_repository import ResidentRepository


# ---------------------------------------------------------------------------
# Fixtures
# ---------------------------------------------------------------------------

@pytest.fixture()
def db_path(tmp_path: object) -> str:
    """Return a path to a fresh, empty SQLite database file for one test.

    ``tmp_path`` is a built-in pytest fixture that provides a temporary
    directory unique to each test invocation.  Using it here ensures every
    test starts with a clean database and tests cannot interfere with each
    other.
    """
    return str(tmp_path / "test_csms.db")  # type: ignore[operator]


@pytest.fixture()
def repo(db_path: str) -> ResidentRepository:
    """Return a ResidentRepository backed by the test database."""
    return ResidentRepository(db_path)


def make_resident(**overrides: object) -> Resident:
    """Build an unsaved Resident with valid defaults.

    ``id`` is intentionally left at its default of ``None`` to represent a
    Resident that has not yet been persisted.
    """
    values: dict[str, object] = {
        "first_name": "Juan",
        "last_name": "Dela Cruz",
        "address": "Barangay Santo Tomas",
        "contact_number": "09171234567",
        "email": "juan@example.com",
        "status": "Active",
    }
    values.update(overrides)
    return Resident(**values)  # type: ignore[arg-type]


# ---------------------------------------------------------------------------
# TEST 1 – Persist a Resident
# ---------------------------------------------------------------------------

def test_persist_a_resident(repo: ResidentRepository) -> None:
    """A valid Resident can be saved through the repository without error."""
    resident = make_resident()

    # save() must complete without raising an exception.
    saved = repo.save(resident)

    assert saved is resident  # same object is returned


# ---------------------------------------------------------------------------
# TEST 2 – Resident Receives an Identifier
# ---------------------------------------------------------------------------

def test_resident_receives_an_identifier(repo: ResidentRepository) -> None:
    """After saving, the Resident has a non-None identifier assigned by the DB.

    The identifier must not be manually hard-coded: it is generated by
    SQLite's AUTOINCREMENT mechanism so the caller never supplies it.
    """
    resident = make_resident()
    assert resident.id is None  # no id before saving

    repo.save(resident)

    assert resident.id is not None
    assert isinstance(resident.id, int)


# ---------------------------------------------------------------------------
# TEST 3 – Retrieve Resident by Identifier
# ---------------------------------------------------------------------------

def test_retrieve_resident_by_identifier(repo: ResidentRepository) -> None:
    """A Resident saved and then retrieved by its id is the correct record."""
    resident = make_resident()
    repo.save(resident)
    assigned_id = resident.id

    retrieved = repo.find_by_id(assigned_id)  # type: ignore[arg-type]

    assert retrieved is not None
    assert retrieved.id == assigned_id


# ---------------------------------------------------------------------------
